##
## Approach: Amortized factorized (mean-field) variational inference.
##
## Reference papers and textbook:
##
## Bishop, Christopher M. (2006).
## "Pattern Recognition and Machine Learning", Springer.
## https://www.microsoft.com/en-us/research/publication/pattern-recognition-machine-learning/
##
## Blei, D. M., Kucukelbir, A. and McAuliffe, J. D. (2017).
## "Variational Inference: A Review for Statisticians."
## In "Journal of the American Statistical Association", vol. 112, no. 518, pp. 859–877.
## https://doi.org/10.1080/01621459.2017.1285773
##
## Margossian, C. C. and Blei, D. M. (2024).
## "Amortized Variational Inference: When and Why?"
## In "Proceedings of the Fortieth Conference on Uncertainty in Artificial Intelligence".
